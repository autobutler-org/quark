-- starts_at, ends_at and repeat_until are TEXT in SQLite too: RFC 3339 strings
-- the queries compare as text, hence COLLATE "C": a locale collation would
-- not order them byte by byte as SQLite does.
CREATE TABLE calendar_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calendar_id BIGINT NOT NULL REFERENCES calendars (id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    notes TEXT NOT NULL DEFAULT '',
    location TEXT NOT NULL DEFAULT '',
    starts_at TEXT COLLATE "C" NOT NULL,
    ends_at TEXT COLLATE "C" NOT NULL,
    all_day BIGINT NOT NULL DEFAULT 0 CHECK (all_day IN (0, 1)),
    time_zone TEXT NOT NULL DEFAULT '',
    repeat TEXT NOT NULL DEFAULT 'none' CHECK (repeat IN ('none', 'daily', 'weekly', 'monthly')),
    reminder_minutes BIGINT CHECK (
        reminder_minutes IS NULL
        OR reminder_minutes BETWEEN CASE all_day
            WHEN 1 THEN -1439
            ELSE 0
        END AND 10080
    ),
    color_index BIGINT NOT NULL DEFAULT 0 CHECK (color_index IN (0, 1, 2, 3, 4, 5)),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT REFERENCES users (id) ON DELETE SET NULL,
    -- SQLite: GLOB '[0-9][0-9][0-9][0-9]-[0-1][0-9]-[0-3][0-9]T00:00:00Z'.
    repeat_until TEXT COLLATE "C" CHECK (
        repeat_until IS NULL
        OR (
            repeat != 'none'
            AND repeat_until ~ '^[0-9]{4}-[0-1][0-9]-[0-3][0-9]T00:00:00Z$'
        )
    )
);

CREATE INDEX idx_calendar_events_start ON calendar_events (calendar_id, starts_at);

CREATE INDEX idx_calendar_events_created_by ON calendar_events (created_by);

