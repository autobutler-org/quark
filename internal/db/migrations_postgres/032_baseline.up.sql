-- The PostgreSQL schema, equivalent to the SQLite schema after its migration
-- 032 (internal/db/migrations). It takes that number so that every later
-- migration has the same number in both sets. internal/db/AGENTS.md has the
-- rules; the type choices below follow its mapping, which is what makes sqlc
-- generate the same Go types for both engines.
--
-- Not here: content search. SQLite's file_content_fts is an FTS5 table kept
-- current by three triggers, and its PostgreSQL counterpart, a tsvector column
-- and a GIN index, is 041_content_search. The file_content table itself is
-- here, because generated queries write to it.

-- Functions named after SQLite ones, so a shared query can call them under one
-- spelling (rule 16 in sql/queries/AGENTS.md). Each implements only the form
-- the shared queries use and rejects or omits the rest: widen one, and its
-- test in internal/db/pgdb, when a query needs more of it.
--
-- datetime('now', modifier): the database's clock moved by a modifier.
-- Used by FailExhaustedStaleJobs, RequeueStaleJobs (sql/queries/jobs.sql) and
-- ClaimMaintenanceRun (sql/queries/maintenance.sql), all with the modifier
-- '-N seconds' and N never negative. A SQLite modifier of the shape
-- '<signed number> <unit>' is valid interval text; the others ('start of
-- day', 'weekday 0' and the like) are not, and fail the cast. Any base but
-- 'now' raises, so a call on a column or a date string fails loudly. There is
-- no one-argument form: queries write CURRENT_TIMESTAMP.
CREATE FUNCTION datetime (base TEXT, modifier TEXT) RETURNS TIMESTAMPTZ
LANGUAGE plpgsql STABLE AS $$
BEGIN
    IF base <> 'now' THEN
        RAISE EXCEPTION 'datetime(): only the base ''now'' is supported, got %', base;
    END IF;
    RETURN CURRENT_TIMESTAMP + modifier::INTERVAL;
END;
$$;

-- json_extract(doc, path): one value out of JSON held in a TEXT column, as
-- text. Used by GetActiveBackupJob (sql/queries/jobs.sql) and by
-- idx_jobs_backup_target below, which must use the same expression as the
-- query to serve it; IMMUTABLE is what lets an index call it. It supports
-- one path, plain member access ('$.a.b'), where SQLite's syntax is also
-- SQL/JSON's. It does not support several paths in one call, and a JSON
-- object or array comes back as its text, not as SQLite's JSON subtype.
CREATE FUNCTION json_extract (doc TEXT, path TEXT) RETURNS TEXT
LANGUAGE sql IMMUTABLE AS $$
    SELECT jsonb_path_query_first(doc::jsonb, path::jsonpath) #>> '{}'
$$;

