CREATE FUNCTION chat_reactions_tombstone () RETURNS trigger AS $$
BEGIN
    DELETE FROM chat_reactions WHERE message_id = NEW.id;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER chat_reactions_tombstone
AFTER UPDATE OF deleted_at ON chat_messages FOR EACH ROW
WHEN (NEW.deleted_at IS NOT NULL)
EXECUTE FUNCTION chat_reactions_tombstone ();

