-- Music library cache (#2982), the PostgreSQL half of 033_music_library.
-- Column order, nullability and types follow internal/db/AGENTS.md so sqlc
-- generates the same Go types as the SQLite table.
--
-- Not here: music_tracks_fts and its triggers. They are FTS5. Music search
-- follows content search onto PostgreSQL (#2958), the same way file_content_fts
-- stayed out of 032_baseline. The music_tracks table is here because the
-- shared queries write to it.

CREATE TABLE music_tracks (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    serial          TEXT    NOT NULL,
    rel_path        TEXT    NOT NULL,
    size            BIGINT  NOT NULL,
    mtime           BIGINT  NOT NULL,
    scanner_version BIGINT  NOT NULL,
    title           TEXT    NOT NULL DEFAULT '',
    artist          TEXT    NOT NULL DEFAULT '',
    album_artist    TEXT    NOT NULL DEFAULT '',
    album           TEXT    NOT NULL DEFAULT '',
    album_key       TEXT    NOT NULL DEFAULT '',
    genre           TEXT    NOT NULL DEFAULT '',
    track_no        BIGINT,
    disc_no         BIGINT,
    year            BIGINT,
    duration_ms     BIGINT,
    duration_exact  BIGINT  NOT NULL DEFAULT 1,
    cover_source    TEXT    NOT NULL DEFAULT '',
    cover_key       TEXT    NOT NULL DEFAULT '',
    UNIQUE (serial, rel_path)
);

CREATE INDEX idx_music_tracks_album ON music_tracks (album_key);

CREATE INDEX idx_music_tracks_artist ON music_tracks (LOWER(album_artist));

CREATE INDEX idx_music_tracks_genre ON music_tracks (LOWER(genre));
