-- The filename index (#2956), the PostgreSQL half of 044_file_index; that
-- file says what the columns hold.
--
-- dir and name sort and compare byte by byte, as SQLite's do: a folder's
-- subtree is a range of dir, and search pages through rows in (dir, name)
-- order, both of which a locale collation would break.
--
-- There is no counterpart of file_index_fts yet: a substring search reads
-- search_name row by row here. pg_trgm is the index to add when it matters.
CREATE TABLE file_index (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    serial TEXT COLLATE "C" NOT NULL,
    dir TEXT COLLATE "C" NOT NULL,
    name TEXT COLLATE "C" NOT NULL,
    search_name TEXT NOT NULL,
    is_dir BOOLEAN NOT NULL,
    size BIGINT NOT NULL,
    mod_time BIGINT NOT NULL,
    indexed_at BIGINT NOT NULL,
    UNIQUE (serial, dir, name)
);

-- instr(haystack, needle): where needle first starts in haystack, counting
-- characters from 1, or 0 when it does not occur; 1 for an empty needle. The
-- SQLite function of the same name (sql/queries/AGENTS.md rule 16), for
-- ListIndexedFilesPage's substring match. Only the two-TEXT form is defined;
-- SQLite's BLOB form has no use here.
CREATE FUNCTION instr (haystack TEXT, needle TEXT) RETURNS BIGINT
    AS $$ SELECT CAST(strpos(haystack, needle) AS BIGINT) $$
    LANGUAGE SQL IMMUTABLE STRICT;
