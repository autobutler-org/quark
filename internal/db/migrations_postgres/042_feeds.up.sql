-- Feed subscriptions (#3714), the PostgreSQL half of 042_feeds.
-- Column order, nullability and types follow internal/db/AGENTS.md so sqlc
-- generates the same Go types as the SQLite tables.
--
-- url can carry a private token. It is a credential: see the SQLite migration.

CREATE TABLE feeds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    url TEXT NOT NULL CHECK (length(url) > 0),
    title TEXT NOT NULL DEFAULT '',
    name TEXT NOT NULL DEFAULT '',
    site_link TEXT NOT NULL DEFAULT '',
    icon TEXT NOT NULL DEFAULT '',
    folder TEXT NOT NULL DEFAULT '',
    etag TEXT NOT NULL DEFAULT '',
    last_modified TEXT NOT NULL DEFAULT '',
    last_fetched_at TIMESTAMPTZ,
    last_error TEXT NOT NULL DEFAULT '',
    consecutive_failures BIGINT NOT NULL DEFAULT 0 CHECK (consecutive_failures >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, url)
);

CREATE TABLE feed_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feed_id BIGINT NOT NULL REFERENCES feeds (id) ON DELETE CASCADE,
    guid TEXT NOT NULL CHECK (length(guid) > 0),
    url TEXT NOT NULL DEFAULT '',
    title TEXT NOT NULL DEFAULT '',
    author TEXT NOT NULL DEFAULT '',
    published_at TIMESTAMPTZ,
    fetched_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    content TEXT NOT NULL DEFAULT '',
    content_hash TEXT NOT NULL DEFAULT '',
    UNIQUE (feed_id, guid)
);
