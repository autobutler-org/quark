-- Chat polls (#3893), the PostgreSQL half of 043_chat_polls. Column order,
-- nullability and types follow internal/db/AGENTS.md so sqlc generates the
-- same Go types as the SQLite tables.

CREATE TABLE chat_polls (
    message_id BIGINT PRIMARY KEY REFERENCES chat_messages (id) ON DELETE CASCADE,
    closes_at TIMESTAMPTZ,
    closed_at TIMESTAMPTZ,
    allow_change BOOLEAN NOT NULL,
    anonymous BOOLEAN NOT NULL,
    results_after_close BOOLEAN NOT NULL
);

CREATE TABLE chat_poll_answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id BIGINT NOT NULL REFERENCES chat_polls (message_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    key_version BIGINT NOT NULL,
    ciphertext BYTEA NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (message_id, user_id)
);

CREATE FUNCTION chat_polls_tombstone () RETURNS trigger AS $$
BEGIN
    DELETE FROM chat_polls WHERE message_id = NEW.id;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER chat_polls_tombstone
AFTER UPDATE OF deleted_at ON chat_messages FOR EACH ROW
WHEN (NEW.deleted_at IS NOT NULL)
EXECUTE FUNCTION chat_polls_tombstone ();
